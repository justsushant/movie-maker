class TestSubtitleOverlayOnEngineFrames:
    """Test subtitle rendering over engine-generated frames.
    
    **Validates: Requirements 7.1, 7.2, 7.3**
    """
    
    def test_subtitle_overlay_on_static_motion(
        self, test_images_dir, test_subtitle_data, subtitle_config, image_loader
    ):
        """Subtitles should render correctly over STATIC motion frames."""
        # Create scene with STATIC motion
        scene = Scene(
            clips=[
                ImageClip(
                    source=test_images_dir / "landscape_1920x1080.png",
                    duration=4.0,
                    motion=MotionPreset.STATIC
                )
            ],
            resolution=(1920, 1080),
            fps=30
        )
        
        # Plan and create renderer
        planner = ScenePlanner()
        timeline = planner.plan(scene, image_loader)
        frame_renderer = FrameRenderer(timeline, image_loader)
        
        # Create subtitle components
        subtitle_source = JsonSubtitleSource(test_subtitle_data)
        layout = SentenceLayout()
        renderer = PillowSubtitleRenderer()
        
        # Render frame with subtitles at t=0.5
        base_frame = frame_renderer.render_frame(0.5)
        base_image = Image.fromarray(base_frame)
        
        # Get subtitle segments
        segments = subtitle_source.get_segments_for_time(0.5)
        
        # Create layout context
        context = SubtitleLayoutContext.from_config(1920, 1080, subtitle_config)
        
        # Layout and render subtitles
        layout_items = layout.layout_frame(0.5, segments, context, subtitle_config)
        final_image = renderer.render_frame(
            base_image, layout_items, subtitle_config, context
        )
        
        # Verify final image
        assert isinstance(final_image, Image.Image)
        assert final_image.size == (1920, 1080)
        
        # Convert to numpy and verify it's different from base frame
        final_array = np.array(final_image)
        diff = np.mean(np.abs(final_array.astype(float) - base_frame.astype(float)))
        
        # Subtitles should add visible content
        assert diff > 0.1, "Subtitles should be visible on frame"
    
    def test_subtitle_overlay_on_ken_burns_zoom_in(
        self, test_images_dir, test_subtitle_data, subtitle_config, image_loader
    ):
        """Subtitles should render correctly over KEN_BURNS_ZOOM_IN motion frames."""
        # Create scene with Ken Burns zoom in
        scene = Scene(
            clips=[
                ImageClip(
                    source=test_images_dir / "landscape_gradient_1920x1080.png",
                    duration=4.0,
                    motion=MotionPreset.KEN_BURNS_ZOOM_IN
                )
            ],
            resolution=(1920, 1080),
            fps=30
        )
        
        # Plan and create renderer
        planner = ScenePlanner()
        timeline = planner.plan(scene, image_loader)
        frame_renderer = FrameRenderer(timeline, image_loader)
        
        # Create subtitle components
        subtitle_source = JsonSubtitleSource(test_subtitle_data)
        layout = SentenceLayout()
        renderer = PillowSubtitleRenderer()
        
        # Render frames with subtitles at different times
        times = [0.5, 1.5, 2.5, 3.5]
        final_frames = []
        
        for t in times:
            base_frame = frame_renderer.render_frame(t)
            base_image = Image.fromarray(base_frame)
            
            segments = subtitle_source.get_segments_for_time(t)
            
            context = SubtitleLayoutContext.from_config(1920, 1080, subtitle_config)
            
            layout_items = layout.layout_frame(t, segments, context, subtitle_config)
            final_image = renderer.render_frame(
                base_image, layout_items, subtitle_config, context
            )
            
            final_frames.append(np.array(final_image))
        
        # Verify all frames are valid
        for frame in final_frames:
            assert frame.shape == (1080, 1920, 3)
            assert frame.dtype == np.uint8
        
        # Verify frames are different (motion is happening)
        diff_0_1 = np.mean(np.abs(
            final_frames[0].astype(float) - final_frames[1].astype(float)
        ))
        assert diff_0_1 > 1.0, "Ken Burns motion should be visible"
    
